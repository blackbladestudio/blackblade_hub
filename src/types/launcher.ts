export type GameVariant = 'Shipping' | 'Development' | 'Test';

export const GAME_VARIANTS: GameVariant[] = ['Shipping', 'Development', 'Test'];

export interface BuildInfo {
  version: string;
  buildNumber: string;
  variant: GameVariant;
  /** For zip: the zip object key. For directory: the key prefix (trailing slash). */
  objectKey: string;
  size: number;
  timestamp: string;
  exeRelativePath: string;
  notes?: string;
  /** True when the build is a directory of files, not a single zip archive */
  isDirectory?: boolean;
}

/**
 * Either published as launcher-manifest.json by CI, or
 * auto-generated by the launcher via S3 object listing.
 */
export interface LauncherManifest {
  game: string;
  platform: string;
  builds: BuildInfo[];
}

export interface InstalledBuild {
  version: string;
  buildNumber: string;
  variant: GameVariant;
  installedAt: string;
  exePath: string;
  installDir: string;
  size: number;
}

export interface LauncherState {
  installBaseDir: string;
  installed: Partial<Record<GameVariant, InstalledBuild>>;
  /** 主界面「启动游戏」默认启动的包体；未设置时回退到第一个已安装的包体 */
  defaultVariant?: GameVariant;
}

export interface DownloadProgress {
  variant: GameVariant;
  phase: 'downloading' | 'verifying' | 'extracting' | 'done' | 'error';
  percent: number;
  downloadedBytes?: number;
  totalBytes?: number;
  downloadedFiles?: number;
  totalFiles?: number;
  speed?: number;
  message?: string;
}
